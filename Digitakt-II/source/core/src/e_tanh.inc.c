static float au_tanhf(float x)
{
    uint32_t bits, ndnan;
    int32_t idxs;
    const uint32_t *c;
    float y, r, f[8];
    int k;
    memcpy(&bits, &x, 4);
    if (x != x)
        return x;
    ndnan = bits & 0x7fe00000u;
    idxs = (int32_t)ndnan - 0x3d400000;
    if (idxs < 0)
        idxs = 0;
    if (idxs > 0x3e00000)
        idxs = 0x3e00000;
    c = AU_TANH_LUT[(uint32_t)idxs >> 21];
    for (k = 0; k < 8; k++)
        memcpy(&f[k], &c[k], 4);
    y = fabsf(x) - f[7];
    r = fmaf(f[0], y, f[1]);
    r = fmaf(r, y, f[2]);
    r = fmaf(r, y, f[3]);
    r = fmaf(r, y, f[4]);
    r = fmaf(r, y, f[5]);
    r = fmaf(r, y, f[6]);
    if (!((int32_t)ndnan <= 0x7f000000))
        r = 1.0f;
    {
        uint32_t rb;
        memcpy(&rb, &r, 4);
        rb |= bits & 0x80000000u;
        memcpy(&r, &rb, 4);
    }
    return r;
}
